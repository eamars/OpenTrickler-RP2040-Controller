#!/usr/bin/env python3
"""Copies the parts of src/powder_analysis.cpp that the previews reuse unchanged.

    extract_sources.py draw <powder_analysis.cpp> <out.cpp>   result texts + display drawing + state names
    extract_sources.py rest <powder_analysis.cpp> <out.cpp>   result texts + state names + REST handlers

The module itself cannot be compiled on a PC (FreeRTOS, pico-sdk, lwIP), so the self-contained
sections are cut out by their comment banners. If a banner changes, this script fails loudly.
"""
import sys

mode, src_path, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
lines = open(src_path).read().split("\n")


def index_of(text, start=0):
    for i in range(start, len(lines)):
        if lines[i].startswith(text):
            return i
    raise SystemExit("marker not found in %s: %r" % (src_path, text))


def banner_before(i):
    """Index of the '// ----' line that starts the banner above line i"""
    while not lines[i].startswith("// ----"):
        i -= 1
    return i


def function_block(text):
    start = index_of(text)
    end = start
    while lines[end] != "}":
        end += 1
    return lines[start:end + 1]


texts = lines[index_of("// Short texts for the result screens"):banner_before(index_of("// User input: display buttons"))]
state_names = function_block("const char * powder_analysis_state_to_string(")

if mode == "draw":
    draw = lines[banner_before(index_of("// Layout: title and line")):index_of("static void render_task(")]
    parts = texts + [""] + draw + [""] + state_names
elif mode == "rest":
    rest = lines[banner_before(index_of("// REST interface")):]
    parts = texts + [""] + state_names + [""] + rest
else:
    raise SystemExit("mode must be draw or rest")

with open(out_path, "w") as f:
    f.write("// Generated by extract_sources.py from %s, do not edit\n" % src_path)
    f.write("\n".join(parts))
    f.write("\n")
print("%s: %d lines" % (out_path, len(parts)))
