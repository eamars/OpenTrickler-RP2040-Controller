#!/usr/bin/env python3
"""Assembles the preview: web scenario pages, display PNGs and out/index.html.

    build_preview.py <src/html/powder_analysis.html> <build/scenarios.json> <out dir>

Standard library only (no Pillow): the PNGs are written by lcd_png.py.
Besides the preview pages (with a banner) a second copy of every scenario goes to out/web/doc/:
no banner, plus a small script that doc_images.py uses for the manual's screenshots.
"""
import json
import os
import sys

from lcd_png import read_pbm, lcd_rows, write_png

page_path, scenarios_path, out_dir = sys.argv[1], sys.argv[2], sys.argv[3]

# ---------------------------------------------------------------------------------------------
# Web scenarios: the real page plus a fetch() replacement with canned responses
# ---------------------------------------------------------------------------------------------
MOCK_SCRIPT = """
<script>
// Preview mock (generated by tools/powder_analysis_preview): canned device responses, no device needed
(function () {
    const scenario = %s;
    const profiles = {"s0": {"0": "AR2208,gr", "1": "AR2209,gr", "2": "8208XBR,gr", "3": "Benchmark2,gr",
                             "4": "N135 stick", "5": "analysis_1", "6": "Profile6", "7": "Profile7"}, "s1": 0};
    let tick = 0;
    let traceSet = 0;

    function statusBody() {
        const s = JSON.parse(JSON.stringify(scenario.state));
        // "Running" scenarios move a little with every poll so the live chart draws something
        if (scenario.live === 'trial') {
            s.el = Math.round((s.el + tick * 0.4) * 10) / 10;
            s.w = Math.min(s.tw - 0.3, Math.round((s.w + tick * 1.1) * 1000) / 1000);
        }
        if (scenario.live === 'flooding') {
            s.w = Math.round((s.w + tick * 0.6) * 1000) / 1000;
        }
        if (scenario.traces.length > 0) {
            s.tid = traceSet + 1;       // the page fetches a recording whenever this changes
        }
        tick += 1;
        return s;
    }

    function traceBody(from) {
        const chunks = scenario.traces[traceSet];
        const chunk = chunks[Math.floor(from / 40)] || chunks[chunks.length - 1];
        // After the last chunk of this recording the "device" has the next one ready
        if (from + chunk.s.length >= chunk.n && traceSet < scenario.traces.length - 1) {
            traceSet += 1;
        }
        return chunk;
    }

    window.fetch = async function (uri) {
        let body;
        if (uri.includes('/rest/powder_analysis_trace')) {
            body = traceBody(parseInt((uri.split('from=')[1] || '0'), 10));
        }
        else if (uri.includes('/rest/powder_analysis_trials')) {
            body = scenario.trials;
        }
        else if (uri.includes('/rest/profile_summary')) {
            body = profiles;
        }
        else {
            body = statusBody();        // commands are accepted but change nothing in the preview
        }
        return { ok: true, status: 200, json: async () => body, text: async () => JSON.stringify(body) };
    };
})();
</script>
"""

# Hooks for the documentation screenshots (doc_images.py), controlled by the query string:
#   ?w=<px>            lay the page out this wide (headless Chrome ignores window widths below ~500)
#   ?show=<a,b,...>    show only these sections: setup, status, result, chart, protocol, test
# All <details> are opened and the settled page height is put into the title for the tool.
DOC_SCRIPT = """
<style>.doc-hidden { display: none !important; }</style>
<script>
(function () {
    const params = new URLSearchParams(location.search);
    const width = params.get('w');
    if (width) {
        document.documentElement.style.width = width + 'px';
        document.body.style.width = width + 'px';
        const nav = document.querySelector('.btm-nav');
        nav.style.right = 'auto';
        nav.style.width = width + 'px';
    }
    const show = params.get('show');
    if (show) {
        const anchors = { setup: '#setupSection', status: '#weight', result: '#resultSection',
                          chart: '#chart', protocol: '#trialRows', test: '#traceChart' };
        const keep = show.split(',').map(name => document.querySelector(anchors[name]).closest('main > *'));
        for (const el of document.querySelector('main').children) {
            if (!keep.includes(el)) {
                el.classList.add('doc-hidden');     // a class, the page itself sets style.display on some sections
            }
        }
        document.querySelector('.btm-nav').classList.add('doc-hidden');
        document.querySelector('main').style.paddingBottom = '8px';
    }
    for (const details of document.querySelectorAll('details')) {
        details.open = true;
    }
    // Number inputs are shown in the system's number format (23,10 on a German Mac); as text they show the value as is
    for (const input of document.querySelectorAll('input[type=number]')) {
        input.type = 'text';
    }
    setTimeout(() => { document.title = 'height=' + document.documentElement.scrollHeight; }, 1500);
})();
</script>
"""

page = open(page_path, encoding="utf-8").read()
marker = "\n<script>"
assert page.count(marker) == 1, "expected exactly one <script> block in the page"

scenarios = [json.loads(line) for line in open(scenarios_path) if line.strip()]
web_dir = os.path.join(out_dir, "web")
os.makedirs(web_dir, exist_ok=True)
for scenario in scenarios:
    banner = ('<div style="background:#ffe9a8;padding:6px 10px;font-family:sans-serif;font-size:0.9em;">'
              'Preview with dummy data: <b>%s</b> - %s</div>' % (scenario["name"], scenario["description"]))
    mocked = page.replace(marker, MOCK_SCRIPT % json.dumps(scenario) + marker, 1)
    with open(os.path.join(web_dir, scenario["name"] + ".html"), "w", encoding="utf-8") as f:
        f.write(mocked.replace("<body>", "<body>\n" + banner, 1))
    os.makedirs(os.path.join(web_dir, "doc"), exist_ok=True)
    with open(os.path.join(web_dir, "doc", scenario["name"] + ".html"), "w", encoding="utf-8") as f:
        f.write(mocked.replace("</body>", DOC_SCRIPT + "</body>", 1))

# ---------------------------------------------------------------------------------------------
# Display screens: PBM (from display_preview) -> PNG scaled 4x, LCD look. The PBM stays for doc_images.py.
# ---------------------------------------------------------------------------------------------
display_dir = os.path.join(out_dir, "display")
screens = json.load(open(os.path.join(display_dir, "screens.json")))
for screen in screens:
    pbm_path = os.path.join(display_dir, screen["file"].replace(".png", ".pbm"))
    write_png(os.path.join(display_dir, screen["file"]), lcd_rows(read_pbm(pbm_path)))

# ---------------------------------------------------------------------------------------------
# Index
# ---------------------------------------------------------------------------------------------
html = ["""<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><title>Powder analysis preview</title>
<style>
body { font-family: sans-serif; margin: 16px; background: #f4f4f4; color: #222; }
h1 { font-size: 1.4em; } h2 { font-size: 1.1em; margin-top: 28px; }
.screens { display: grid; grid-template-columns: repeat(auto-fill, minmax(540px, 1fr)); gap: 14px; }
.screen { background: #fff; padding: 10px; border-radius: 6px; box-shadow: 0 1px 2px rgba(0,0,0,0.15); }
.screen img { image-rendering: pixelated; image-rendering: crisp-edges; width: 512px; height: 256px; border: 1px solid #999; display: block; }
.screen .name { font-weight: bold; margin-top: 6px; } .screen .values { color: #666; font-size: 0.85em; }
ul.web li { margin: 6px 0; } ul.web a { font-weight: bold; }
</style></head><body>
<h1>Powder analysis preview (dummy data)</h1>
<p>Generated by <code>make -C tools/powder_analysis_preview</code> from the real drawing code and the real web page.</p>
<h2>Web page scenarios</h2>
<p>Each file is the real <code>powder_analysis.html</code> with canned device responses; opens from disk, polling and charts work.</p>
<ul class="web">"""]
for scenario in scenarios:
    html.append('<li><a href="web/%s.html">%s</a> - %s</li>' % (scenario["name"], scenario["name"], scenario["description"]))
html.append("</ul>\n<h2>Display screens (128x64, scaled 4x)</h2>\n<div class=\"screens\">")
for screen in screens:
    html.append('<div class="screen"><img src="display/%s" alt="%s"><div class="name">%s</div>'
                '<div>%s</div><div class="values">%s</div></div>'
                % (screen["file"], screen["name"], screen["name"], screen["description"], screen["values"]))
html.append("</div></body></html>\n")
open(os.path.join(out_dir, "index.html"), "w", encoding="utf-8").write("\n".join(html))

print("%d web scenarios, %d display screens -> %s/index.html" % (len(scenarios), len(screens), out_dir))
